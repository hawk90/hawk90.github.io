#!/usr/bin/env node
/**
 * Writes each published post's current URL into its frontmatter as `slug:`.
 *
 * Today a post's URL *is* its folder: Astro's glob loader derives the entry id
 * from the file path, so moving a file moves a published page and breaks every
 * link that pointed at it. That coupling is the reason the content tree cannot
 * be reorganised. Setting `slug:` breaks it — the loader substitutes that value
 * for the id, so the URL stops depending on where the file sits.
 *
 * Freezing is only safe if the value written is the URL the site *already*
 * serves. So this does not trust its own path arithmetic: every proposed slug
 * must correspond to a page that exists in `dist/`, which is the last thing
 * actually published. A post whose computed slug has no built page is reported
 * and left alone rather than frozen at a guess.
 *
 * Scope, and what is deliberately left out:
 *
 *   - Drafts. They have no published URL to preserve, and freezing one would
 *     lock in a path it was never served at. They are frozen when published.
 *   - Posts that already carry `slug:`. That is what makes a second run a
 *     no-op.
 *   - `math/linear-algebra/**`, which is generated by `npm run sync:book-notes`
 *     from another repository (CLAUDE.md §12). Editing it here is overwritten
 *     by the next sync, so the freeze belongs upstream.
 *
 * Preview by default; --apply is required. Reports every file it would touch,
 * checks the proposed slugs for collisions with each other and with the posts
 * already frozen, verifies each rewritten frontmatter still parses, and is
 * idempotent.
 *
 * Usage: node scripts/freeze-post-urls.mjs [--apply] [--limit N]
 */
import { readFile, writeFile, readdir, mkdir, access } from 'node:fs/promises';
import { join } from 'node:path';
import * as yaml from 'js-yaml';

const apply = process.argv.includes('--apply');
const limitArg = process.argv.indexOf('--limit');
const limit = limitArg === -1 ? Infinity : Number(process.argv[limitArg + 1]);

const ROOT = 'src/content/blog';
const DIST = 'dist/blog';
/** Generated by `npm run sync:book-notes`; freezing here is undone by the sync. */
const SYNCED = [`${ROOT}/math/linear-algebra/`];

async function walk(dir, out = []) {
  for (const entry of (await readdir(dir, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name))) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) await walk(path, out);
    else if (entry.name.endsWith('.md')) out.push(path);
  }
  return out;
}

const exists = (path) => access(path).then(() => true, () => false);

const files = await walk(ROOT);
const planned = [];
const skipped = new Map();
const problems = [];
const skip = (why, file) => {
  if (!skipped.has(why)) skipped.set(why, []);
  skipped.get(why).push(file);
};

for (const file of files) {
  const text = await readFile(file, 'utf8');
  const block = text.match(/^(---\n)([\s\S]*?)(\n---)/);
  if (!block) { problems.push([file, 'no frontmatter']); continue; }
  const [, open, frontmatter, close] = block;

  let data;
  try { data = yaml.load(frontmatter); } catch (error) {
    problems.push([file, `unparseable frontmatter: ${error.reason ?? error.message}`]);
    continue;
  }

  if (data?.slug) { skip('already frozen', file); continue; }
  if (data?.draft === true) { skip('draft — no published URL yet', file); continue; }
  if (SYNCED.some((prefix) => file.startsWith(prefix))) { skip('synced from book-notes', file); continue; }

  // The id Astro derives from the path today, which is the live URL.
  let route = file.slice(`${ROOT}/`.length, -'.md'.length);
  route = route.replace(/\/index$/, '');

  // Ground truth: the page the last build actually emitted. Without this the
  // script would happily freeze a URL that the site never served.
  if (!(await exists(join(DIST, route, 'index.html')))) {
    problems.push([file, `no built page at /blog/${route}/`]);
    continue;
  }

  planned.push({ file, route, text, open, frontmatter, close });
}

// Two posts frozen at one URL silence one of them, and frontmatter is the one
// place the route audit cannot repair by moving a file.
const claimed = new Map();
for (const file of files) {
  const text = await readFile(file, 'utf8');
  const existing = text.match(/^---\n([\s\S]*?)\n---/)?.[1]?.match(/^slug:\s*(.+)$/m);
  if (existing) claimed.set(existing[1].trim().replace(/^['"]|['"]$/g, ''), file);
}
const collisions = [];
for (const entry of planned) {
  const owner = claimed.get(entry.route);
  if (owner) collisions.push([entry.route, owner, entry.file]);
  else claimed.set(entry.route, entry.file);
}

const writable = collisions.length ? [] : planned.slice(0, limit);

for (const entry of writable) {
  // Placed under `title` so the two identity fields read together.
  const line = `slug: "${entry.route}"`;
  const next = /^title:.*$/m.test(entry.frontmatter)
    ? entry.frontmatter.replace(/^(title:.*)$/m, `$1\n${line}`)
    : `${line}\n${entry.frontmatter}`;
  try { yaml.load(next); } catch (error) {
    problems.push([entry.file, `frontmatter would not parse after freeze: ${error.reason ?? error.message}`]);
    entry.blocked = true;
    continue;
  }
  entry.next = entry.text.replace(block_of(entry), `${entry.open}${next}${entry.close}`);
}
function block_of(entry) { return `${entry.open}${entry.frontmatter}${entry.close}`; }

await mkdir('reports/url-freeze', { recursive: true });
await writeFile('reports/url-freeze/latest.md', [
  '# URL freeze preview',
  '',
  `- Posts scanned: ${files.length}`,
  `- Would freeze: ${planned.length}`,
  `- Already frozen: ${(skipped.get('already frozen') ?? []).length}`,
  ...[...skipped].map(([why, list]) => `- Skipped, ${why}: ${list.length}`),
  `- Collisions: ${collisions.length}`,
  `- Problems: ${problems.length}`,
  '',
  '## Would freeze',
  ...planned.map((entry) => `- \`${entry.file}\` → \`/blog/${entry.route}\``),
  ...(collisions.length ? ['', '## Collisions', ...collisions.map(([route, a, b]) => `- \`/blog/${route}\` claimed by \`${a}\` and \`${b}\``)] : []),
  ...(problems.length ? ['', '## Problems', ...problems.map(([file, why]) => `- \`${file}\` — ${why}`)] : []),
  '',
  '## Skipped',
  ...[...skipped].flatMap(([why, list]) => ['', `### ${why} (${list.length})`, ...list.map((file) => `- \`${file}\``)]),
  '',
].join('\n'));

console.log(`URL freeze: ${planned.length} post(s) would be frozen out of ${files.length} scanned.`);
for (const [why, list] of skipped) console.log(`  skip ${list.length} — ${why}`);
for (const entry of planned.slice(0, 5)) console.log(`  ${entry.file} → /blog/${entry.route}`);
if (planned.length > 5) console.log(`  … ${planned.length - 5} more (reports/url-freeze/latest.md)`);
for (const [route, a, b] of collisions) console.log(`  COLLISION /blog/${route}: ${a} + ${b}`);
for (const [file, why] of problems) console.log(`  problem ${file}: ${why}`);

if (collisions.length) {
  console.log('Refusing to write: freezing a colliding slug hides one of the posts.');
  process.exitCode = 1;
} else if (!apply) {
  console.log('Preview only; pass --apply to write.');
} else {
  let written = 0;
  for (const entry of writable) {
    if (entry.blocked) continue;
    await writeFile(entry.file, entry.next);
    written += 1;
  }
  console.log(`Froze ${written} post URL(s). Re-run scripts/audit-route-collisions.mjs before building.`);
}
