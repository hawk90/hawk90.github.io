#!/usr/bin/env node
// Gives every draft the same URL freeze the published posts already have.
//
// A post's URL comes from frontmatter `slug:` when it is set, and from the file
// path when it is not. The 726 published posts all set it, so their URL and
// their folder are two separate facts that happen to agree; the 2661 drafts do
// not, so for them the URL *is* the folder and moving a file moves the URL.
// That costs nothing today, because a draft has no page to break — it costs on
// the day the post publishes and its current folder silently becomes the
// permanent address.
//
// The value written is the path the file sits at right now, so nothing changes
// for any reader, ever. What changes is that it can now be changed: reorganise
// the tree afterwards and the URLs stay where they are.
//
// Matches the existing convention exactly: `slug: "<path>"` as the line
// directly after `title:`, which is where all 726 published posts carry it.
//
// Files under a synced tree are skipped. `src/content/blog/math/linear-algebra`
// is generated by scripts/sync-book-notes.mjs from ../book-notes, and an edit
// here is erased by the next sync — the generator has to emit the field, not
// this script (CLAUDE.md 12).
//
// Usage:
//   node scripts/freeze-post-slugs.mjs            # preview
//   node scripts/freeze-post-slugs.mjs --apply
//   node scripts/freeze-post-slugs.mjs --limit 5  # preview a sample with diffs

import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';

const argv = process.argv.slice(2);
const apply = argv.includes('--apply');
// Off by default: writing into a generated tree is normally work the next sync
// erases. It is safe here only because sync-book-notes.mjs now emits `slug:`
// with exactly the value computed below, so the two agree and a re-sync
// reproduces the field rather than dropping it. Verify that before using this.
const includeSynced = argv.includes('--include-synced');
const limitArg = argv.indexOf('--limit');
const limit = limitArg === -1 ? 3 : Number(argv[limitArg + 1]);

const ROOT = 'src/content/blog';
// Generated trees: the frontmatter here is output, so it has to be fixed at the
// generator. Listed rather than inferred, so adding a synced series is a
// deliberate edit.
const SYNCED = ['math/linear-algebra'];

/** @param {string} dir @returns {Promise<string[]>} */
async function markdownFiles(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const file = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...await markdownFiles(file));
    else if (entry.name.endsWith('.md')) out.push(file);
  }
  return out;
}

const files = (await markdownFiles(ROOT)).sort();
const planned = [];
const skipped = { hasSlug: 0, synced: [], noFrontmatter: [], noTitle: [] };

for (const file of files) {
  const raw = await readFile(file, 'utf8');
  const id = relative(ROOT, file).replace(/\.md$/, '').replace(/\\/g, '/');

  const frontmatter = raw.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!frontmatter) { skipped.noFrontmatter.push(id); continue; }
  if (/^slug:\s*/m.test(frontmatter[1])) { skipped.hasSlug++; continue; }
  if (!includeSynced && SYNCED.some((prefix) => id.startsWith(`${prefix}/`))) { skipped.synced.push(id); continue; }

  // Insert after the `title:` entry, including any lines it folds onto, so a
  // multi-line title does not get split by the new field.
  const lines = raw.split('\n');
  const titleAt = lines.findIndex((line, i) => i > 0 && /^title:\s*/.test(line));
  if (titleAt === -1) { skipped.noTitle.push(id); continue; }
  let insertAt = titleAt + 1;
  while (insertAt < lines.length && /^\s+\S/.test(lines[insertAt])) insertAt++;

  const next = [...lines];
  next.splice(insertAt, 0, `slug: "${id}"`);
  planned.push({ file, id, before: lines[titleAt], after: next.slice(titleAt, insertAt + 1), content: next.join('\n') });
}

console.log(
  `Post slugs: ${files.length} file(s) — ${planned.length} to freeze, ` +
  `${skipped.hasSlug} already frozen, ${skipped.synced.length} synced (generator's job), ` +
  `${skipped.noFrontmatter.length + skipped.noTitle.length} unparsable.`,
);

if (skipped.synced.length) {
  console.log(`\n  skipped as generated — fix in scripts/sync-book-notes.mjs:`);
  for (const id of skipped.synced.slice(0, 5)) console.log(`    ${id}`);
  if (skipped.synced.length > 5) console.log(`    +${skipped.synced.length - 5} more`);
}
for (const [label, list] of [['no frontmatter', skipped.noFrontmatter], ['no title:', skipped.noTitle]]) {
  if (list.length) { console.log(`\n  skipped (${label}):`); for (const id of list) console.log(`    ${id}`); }
}

if (planned.length) {
  console.log(`\n  change, on ${Math.min(limit, planned.length)} of ${planned.length}:`);
  for (const change of planned.slice(0, limit)) {
    console.log(`\n    ${change.id}`);
    for (const line of change.after) console.log(`    ${line === `slug: "${change.id}"` ? '+' : ' '} ${line}`);
  }
}

// Every URL must still be unique afterwards, and must not collide with a
// category page. Checked before writing, not after.
const urls = new Map();
for (const file of files) {
  const raw = await readFile(file, 'utf8');
  const id = relative(ROOT, file).replace(/\.md$/, '').replace(/\\/g, '/');
  const slug = raw.match(/^slug:\s*(.+)$/m)?.[1]?.trim().replace(/^["']|["']$/g, '') ?? id;
  if (!urls.has(slug)) urls.set(slug, []);
  urls.get(slug).push(id);
}
const collisions = [...urls.entries()].filter(([, v]) => v.length > 1);
if (collisions.length) {
  console.error(`\n! ${collisions.length} URL(s) claimed by more than one post; refusing.`);
  for (const [url, ids] of collisions.slice(0, 10)) console.error(`    ${url}: ${ids.join(', ')}`);
  process.exit(1);
}

if (!apply) {
  console.log(`\nPreview only. ${planned.length} file(s) would change; pass --apply to write.`);
  process.exit(0);
}

for (const change of planned) await writeFile(change.file, change.content);
console.log(`\nFroze ${planned.length} slug(s).`);

// Post-change verification: re-read from disk. Idempotency comes from the same
// `slug:` test that selected the files — a second run finds them frozen and
// plans nothing.
const problems = [];
let frozen = 0;
for (const file of files) {
  const raw = await readFile(file, 'utf8');
  const id = relative(ROOT, file).replace(/\.md$/, '').replace(/\\/g, '/');
  if (!includeSynced && SYNCED.some((prefix) => id.startsWith(`${prefix}/`))) continue;
  const slug = raw.match(/^slug:\s*(.+)$/m)?.[1]?.trim().replace(/^["']|["']$/g, '');
  if (!slug) { problems.push(`${id}: still has no slug`); continue; }
  if (slug !== id) problems.push(`${id}: slug is "${slug}", which is not the path it was frozen at`);
  frozen++;
}
if (problems.length) {
  for (const problem of problems.slice(0, 10)) console.error(`  ! ${problem}`);
  process.exitCode = 1;
} else {
  console.log(`Verified: ${frozen} post(s) carry a slug equal to their current path, ${urls.size} distinct URL(s).`);
}
